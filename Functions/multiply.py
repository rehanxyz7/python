def multiply(p1,p2):
    return p1*p2
print("Enter two numbers :\n")
n= int(input("Enter number 1: \n"))
n2= int(input("Enter number 2: \n"))

mul = multiply(n,n2)
print(f"The result of number multiplication is: {mul}\n ")

print("Enter two strings  :\n")
s= str(input("Enter string 1: \n"))
s2= int(input("Enter string 2: \n"))

mul = multiply(s,s2)
print(f"The result of string  multiplication is: {mul}\n ")